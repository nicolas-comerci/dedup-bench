#!/usr/bin/env python3
import matplotlib
matplotlib.use("Agg")
import seaborn as sns
import matplotlib.pyplot as plt
import os ,sys
import textwrap

# Dictionary to hold throughput values 
throughput_vals = {}
space_savings_vals = {}
dataset_name = ""

rename_dict = { "aemin":"AE-Min",
                "aemax":"AE-Max",
                "crc32":"CRC32",
                "fastcdc":"FastCDC",
                "gear":"Gear",
                "maxp":"MAXP",
                "rabins":"Rabin",
                "ram":"RAM",
                "seqcdc":"SeqCDC",
                "tttd":"TTTD",
                "vaemax128":"VAEMax-128",
                "vaemax256":"VAEMax-256",
                "vaemax512":"VAEMax-512",                
                "vaemin128":"VAEMin-128",
                "vaemin256":"VAEMin-256",
                "vaemin512":"VAEMin-512",
                "vmaxp128":"VMAXP-128",
                "vmaxp256":"VMAXP-256",
                "vmaxp512":"VMAXP-512",
                "vram128":"VRAM-128",
                "vram256":"VRAM-256",
                "vram512":"VRAM-512",
}

preferred_order = [
    "CRC32", "FastCDC", "Gear", "Rabin", "TTTD",
    "AE-Max", "VAEMax-128", "VAEMax-256", "VAEMax-512",
    "AE-Min", "VAEMin-128", "VAEMin-256", "VAEMin-512",
    "MAXP", "VMAXP-128", "VMAXP-256", "VMAXP-512",
    "RAM", "VRAM-128", "VRAM-256", "VRAM-512",
    "SeqCDC",
]

label_wrap_width = 10
minimum_figure_width = 16
label_slot_width = 1.4
minimum_label_gap = 12

def build_custom_order(keys):
    keys = list(keys)
    custom_order = [key for key in preferred_order if key in keys]
    custom_order.extend(key for key in keys if key not in custom_order)
    return custom_order


def wrap_algorithm_label(label):
    return "\n".join(textwrap.wrap(
        label,
        width=label_wrap_width,
        break_long_words=True,
        break_on_hyphens=True,
    ))


def calculate_figure_width(*orders):
    method_count = max((len(order) for order in orders), default=0)
    return max(minimum_figure_width, method_count * label_slot_width)


def ensure_labels_do_not_overlap(fig, axes):
    for _ in range(5):
        fig.canvas.draw()
        required_scale = 1

        for axis in axes:
            label_bounds = [
                label.get_window_extent()
                for label in axis.get_xticklabels()
                if label.get_visible()
            ]
            for left, right in zip(label_bounds, label_bounds[1:]):
                center_distance = right.x0 + right.width / 2 - (left.x0 + left.width / 2)
                required_distance = left.width / 2 + right.width / 2 + minimum_label_gap
                if center_distance > 0:
                    required_scale = max(required_scale, required_distance / center_distance)

        if required_scale <= 1:
            return

        fig.set_size_inches(
            fig.get_figwidth() * required_scale,
            fig.get_figheight(),
            forward=True,
        )
        fig.tight_layout()


def plot_bar_chart(axis, values, order, ylabel, title):
    sns.barplot(
        x=order,
        y=[values[key] for key in order],
        ax=axis,
        gap=0.5,
        hue=order,
        legend=False,
        palette="inferno",
        edgecolor='black',
        order=order,
        hue_order=order,
    )
    axis.set_xticks(range(len(order)))
    axis.set_xticklabels([wrap_algorithm_label(label) for label in order])
    axis.tick_params(axis='x', labelsize=20, pad=8)
    axis.tick_params(axis='y', labelsize=26)
    axis.set_xlabel("CDC Algorithm", fontsize=30)
    axis.set_ylabel(ylabel, fontsize=30)
    axis.set_title(title, fontsize=45)


# Read results.txt generated by dedup_script.sh
def read_src_throughput(results_file_path):
    global throughput_vals, dataset_name
    with open(results_file_path, 'r') as results_file:
        curr_algo = None
        curr_throughput = None
        for line in results_file:
            if("Dataset path:" in line):
                dataset_name = line.split(":")[1].strip()
                if(dataset_name[-1] == "/"):
                    dataset_name = dataset_name[:-1]
                dataset_name = os.path.basename(dataset_name)
            if(".conf" in line):
                curr_algo = line.strip().split(".")[0].strip().split("_")[0].strip()
                if(curr_algo in rename_dict.keys()):
                    curr_algo = rename_dict[curr_algo]
            elif("Chunking Throughput" in line):
                curr_throughput = float(line.strip().split(":")[1].strip()) / 1000 # Convert throughput to GB/s
                if(curr_algo == None):
                    raise Exception("Throughput value detected but no chunking technique? Check results file format for errors.")
                throughput_vals[curr_algo] = curr_throughput
                curr_throughput = None
                curr_algo = None

def read_src_spacesavings(results_file_path):
    global space_savings_vals
    with open(results_file_path, 'r') as results_file:
        curr_algo = None
        space_savings = None
        for line in results_file:
            if(".conf" in line):
                curr_algo = line.strip().split(".")[0].strip().split("_")[0].strip()
                if(curr_algo in rename_dict.keys()):
                    curr_algo = rename_dict[curr_algo]
            elif("Space savings" in line):
                space_savings = float(line.strip().split(":")[1].strip().strip("%"))
                if(curr_algo == None):
                    raise Exception("Space savings value detected but no chunking technique? Check results file format for errors.")
                space_savings_vals[curr_algo] = space_savings
                space_savings = None
                curr_algo = None

# Plot bar graph
def plot_results():
    global throughput_vals
    sns.set_style('darkgrid')
    sns.set_context("poster")
    plt.rcParams['figure.dpi'] = 300

    space_savings_order = build_custom_order(space_savings_vals.keys())
    throughput_order = build_custom_order(throughput_vals.keys())
    figure_width = calculate_figure_width(space_savings_order, throughput_order)
    fig, ax = plt.subplots(2, 1, figsize=(figure_width, 24))

    plot_bar_chart(ax[0], space_savings_vals, space_savings_order,
                   "Space Savings (%)", "Space Savings")
    plot_bar_chart(ax[1], throughput_vals, throughput_order,
                   "Throughput (GB/s)", "Chunking Throughput")

    plt.suptitle("Dataset statistics for " + dataset_name, fontsize=60)
    plt.tight_layout()
    ensure_labels_do_not_overlap(fig, ax)
    
    fig.savefig('results_graph.png')

    

    
if(__name__ == "__main__"):
    if(len(sys.argv) != 2):
        print("Usage: python3 plot_results.py <path_to_results>")
        print("\t <path_to_results>: Path to results.txt file generated by dedup_script.sh")
        sys.exit(0)
    
    results_path = sys.argv[1]
    read_src_throughput(results_path)
    read_src_spacesavings(results_path)
    plot_results()

    print("Throughput and space savings graphs plotted and saved as results_graph.png.")

